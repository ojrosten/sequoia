#!/usr/bin/env python3
"""EXPERIMENT: emit the whole of Source/sequoia as one named module.

Answers one question - what does a translation unit cost when it contains not a
single #include - and answers it by brute force rather than by design. The
output is deliberately *not* committed: it is 28k generated lines, and sequoia
has enough committed generated output already.

    python3 scripts/experiments/generate_monolithic_module.py <out.cppm>

Then, with a std BMI built from libc++'s std.cppm:

    clang++ -std=c++26 -fmodule-file=std=std.pcm -fmodule-file=std.compat=std.compat.pcm \
            -I Source --precompile <out.cppm> -o sequoia.pcm

This is not a migration plan. A real one wants module partitions, the tests
converted too, and a decision about the macros, none of which this does.
"""
import argparse, collections, os, re, sys

INC_QUOTED = re.compile(r'^\s*#include\s+"[^"]+"\s*$', re.M)
INC_ANGLED = re.compile(r'^\s*#include\s+<[^>]+>\s*$', re.M)
PRAGMA     = re.compile(r'^\s*#pragma once\s*$', re.M)
LICENCE    = re.compile(r'^/{60,}\n(?:.*\n)*?^/{60,}\n', re.M)

# Namespace-scope `static` gives internal linkage, which cannot be exported.
# Both of these look vestigial rather than deliberate; patched here rather than
# in the headers, since this script must not change what it is measuring.
INTERNAL_LINKAGE = [
    ("inline constexpr static bool has_abs", "inline constexpr bool has_abs"),
    ("  static bool check_prerequisites",    "  bool check_prerequisites"),
]


def headers(root):
    out = []
    for d, _, fs in os.walk(root):
        out += [os.path.join(d, f) for f in fs if f.endswith(".hpp")]
    return out


def dependencies(hdrs, rel):
    """Quoted includes, resolved both as repo-relative and relative to the includer.

    The second form matters: exactly one header in sequoia includes a sibling by
    bare name, and missing that edge puts it after its own dependency, which
    surfaces a long way away as an undeclared identifier.
    """
    byrel = {rel(h): h for h in hdrs}
    dep = collections.defaultdict(set)
    for h in hdrs:
        for inc in re.findall(r'#include "([^"]+)"', open(h).read()):
            if inc in byrel:
                dep[rel(h)].add(inc)
            else:
                sibling = rel(os.path.normpath(os.path.join(os.path.dirname(h), inc)))
                if sibling in byrel:
                    dep[rel(h)].add(sibling)
    return byrel, dep


def topological(byrel, dep):
    order, done, active = [], set(), set()
    def visit(n):
        if n in done or n in active:
            return
        active.add(n)
        for d in sorted(dep[n]):
            visit(d)
        active.discard(n)
        done.add(n)
        order.append(n)
    for n in sorted(byrel):
        visit(n)
    return order


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("output")
    ap.add_argument("--root", default="Source/sequoia")
    ap.add_argument("--module-name", default="sequoia")
    a = ap.parse_args()

    rel = lambda p: os.path.relpath(p, os.path.dirname(a.root.rstrip("/")) or ".")
    hdrs = headers(a.root)
    byrel, dep = dependencies(hdrs, rel)
    order = topological(byrel, dep)

    parts = []
    for n in order:
        s = open(byrel[n]).read()
        s = LICENCE.sub("", s, count=1)
        s = PRAGMA.sub("", s)
        s = INC_QUOTED.sub("", s)
        s = INC_ANGLED.sub("", s)
        for old, new in INTERNAL_LINKAGE:
            s = s.replace(old, new)
        parts.append(f"// ==== {n} ====\n{s.strip()}\n")

    with open(a.output, "w") as f:
        f.write(f"// Generated by {os.path.basename(__file__)} - do not edit, do not commit.\n"
                f"module;\n\nexport module {a.module_name};\n\n"
                f"import std;\nimport std.compat;\n\nexport {{\n"
                + "\n".join(parts) + "\n}\n")
    print(f"{a.output}: {len(order)} headers, {sum(p.count(chr(10)) for p in parts)} lines", file=sys.stderr)


if __name__ == "__main__":
    main()
